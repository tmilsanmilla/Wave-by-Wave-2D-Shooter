import assert from 'node:assert/strict';
import fs from 'node:fs';
import {bindAccount} from '../../lib/pixel-pulse.js';
import {assertNativeLinkTarget} from '../../api/pixel-pulse.js';
const profile={subject:'10000000-0000-4000-8000-000000000001',username:'fixture_name',email:'fixture@example.invalid'};
const game='20000000-0000-4000-8000-000000000001';
assert.throws(()=>assertNativeLinkTarget('link',null,{cookie:'already-signed-in-pixel'}),{code:'LINK_PROOF'},'a Pixel cookie without a proved native target can never turn explicit Link into Create');
assert.doesNotThrow(()=>assertNativeLinkTarget('continue',null),'ordinary returning bound Continue needs no new native link');
assert.doesNotThrow(()=>assertNativeLinkTarget('link',game),'proved native ownership proceeds to the separate new-link hold');
const calls=[];
const db={async query(sql,args){calls.push({sql,args});return {rows:[],rowCount:0};}};
await assert.rejects(bindAccount(db,profile,game),{code:'LINK_CONFIRMATION_PENDING'});
assert.ok(calls.every(c=>!/^\s*(?:insert|update|delete)/i.test(c.sql)),'a legacy pending callback cannot mutate/create a new link without central password proof');
const owned={async query(sql){if(sql.startsWith('select * from oz_identity.pixel_profiles'))return {rows:[{account_id:game}],rowCount:1};return {rows:[],rowCount:0};}};
await assert.rejects(bindAccount(owned,profile,'30000000-0000-4000-8000-000000000001'),{code:'ALREADY_LINKED'},'an existing link may never be switched to another game UUID');
const returning={async query(sql){
 if(sql.startsWith('select * from oz_identity.pixel_profiles'))return {rows:[{account_id:game}],rowCount:1};
 if(sql.startsWith('select * from oz_identity.accounts'))return {rows:[{id:game,email:profile.email,deleted_at:null}],rowCount:1};
 if(sql.startsWith('select subject from oz_identity.pixel_profiles'))return {rows:[{subject:profile.subject}],rowCount:1};
 if(sql.startsWith('select user_id from public.social_profiles'))return {rows:[{user_id:game}],rowCount:1};
 return {rows:[],rowCount:0};
}};
assert.equal(await bindAccount(returning,profile,null),game,'a returning already-linked subject retains the exact original account');
const legacy={async query(sql){
 if(sql.startsWith('select * from oz_identity.pixel_profiles'))return {rows:[],rowCount:0};
 if(sql.startsWith('select 1 from oz_identity.accounts'))return {rows:[{}],rowCount:1};
 if(/^\s*(?:insert|update|delete)/i.test(sql))throw new Error('Implicit legacy adoption attempted');
 return {rows:[],rowCount:0};
}};
await assert.rejects(bindAccount(legacy,profile,null),{code:'LINK_CONFIRMATION_PENDING'},'a remembered central email cannot implicitly adopt an existing game account');
const freshCalls=[];
const fresh={async query(sql){freshCalls.push(sql);return {rows:[],rowCount:0};}};
await assert.rejects(bindAccount(fresh,profile,null),{code:'LINK_CONFIRMATION_PENDING'},'a unique email cannot create a first Pixel account or binding through Continue/Create');
assert.ok(freshCalls.every(sql=>!/^\s*(?:insert|update|delete)/i.test(sql)),'first binding is rejected before any identity/profile/session writes');
assert.ok(!freshCalls.some(sql=>sql.includes('oz_identity.accounts')),'an unbound subject cannot probe native accounts by email');
const api=fs.readFileSync(new URL('../../api/pixel-pulse.js',import.meta.url),'utf8');
assert.match(api,/if\(linkAccountId&&![\s\S]{0,150}pixel_profiles where account_id=\$1/,'new start attempts must check the already-proved native account binding');
assert.ok(api.indexOf("throw failure('LINK_CONFIRMATION_PENDING'")<api.indexOf('insert into oz_identity.pixel_login_attempts'),'blocked new links cannot create login attempts');
assert.ok(api.includes('assertNativeLinkTarget(intent,linkAccountId)'),'link intent without ownership must never fall back to account creation');
assert.ok(api.indexOf('assertNativeLinkTarget(intent,linkAccountId)')<api.indexOf('insert into oz_identity.pixel_login_attempts'),'cookie-only Link must fail before creating any attempt');
console.log('PASS all first-binding holds, no mutation/email probing, preserved existing links and no cookie-only confirmation claim');
