import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const networking=fs.readFileSync(new URL('../js/networking.js',import.meta.url),'utf8');
const social=fs.readFileSync(new URL('../js/social.js',import.meta.url),'utf8');
const migration=fs.readFileSync(new URL('../../neon/migrations/004-username-30-day-guard.sql',import.meta.url),'utf8');
const start=networking.indexOf('async function neonBetterAuthConfirmUsername(');
const helper=networking.slice(start,networking.indexOf('\nasync function ',start+1));
let actualRow={user_id:'game-original',username:'saved_name'},calls=0,error=null;
const client={async rpc(name){calls++;assert.equal(name,'get_my_outpost_zero_username');return {data:actualRow?[actualRow]:[],error};}};
const context=vm.createContext({sb:client,neonBetterAuthUnavailable:()=>new Error('Unavailable'),
 neonAccountAccessError:e=>Object.assign(new Error(e.code),e),authUser:null});
vm.runInContext(helper,context);
const original={id:'game-original',neon_auth_id:'native-original',email:'fixture@example.invalid',user_metadata:{old:'keep'}};
const saved=await context.neonBetterAuthConfirmUsername('saved_name',original);
assert.equal(saved.error,null);assert.equal(saved.data.user.id,'game-original');assert.equal(saved.data.user.neon_auth_id,'native-original');
assert.equal(saved.data.user.user_metadata.username,'saved_name');assert.equal(saved.data.user.user_metadata.old,'keep');
actualRow={user_id:'other-game',username:'saved_name'};
assert.equal((await context.neonBetterAuthConfirmUsername('saved_name',original)).error.code,'NEON_USERNAME_NOT_CONFIRMED');
actualRow={user_id:'game-original',username:'operator'};
assert.equal((await context.neonBetterAuthConfirmUsername('saved_name',original)).error.code,'NEON_USERNAME_NOT_CONFIRMED');
error={code:'SESSION_ERROR'};
assert.equal((await context.neonBetterAuthConfirmUsername('saved_name',original)).error.code,'SESSION_ERROR');
assert.ok(calls===4);
error=null;actualRow=null;
assert.equal((await context.neonBetterAuthConfirmUsername('',original)).error,null,'a new account with no chosen name may continue to the claim screen');
assert.equal((await context.neonBetterAuthConfirmUsername('saved_name',original)).error.code,'NEON_USERNAME_NOT_CONFIRMED');
actualRow={user_id:'game-original',username:'saved_name'};
const restored=await context.neonBetterAuthConfirmUsername('',{...original,user_metadata:{displayName:'operator'}});
assert.equal(restored.data.user.user_metadata.username,'saved_name','a stale native-cookie label cannot reopen the claim gate on another login');
assert.ok((await context.neonBetterAuthConfirmUsername('saved_name',{})).error,'no game identity cannot produce a false success');
assert.doesNotMatch(helper,/getSession|updateUser/,'claim confirmation must not depend on cached Auth metadata or an additional account mutation');
assert.doesNotMatch(social,/sb\.auth\.updateUser\(\{data:\{username:/,'the ignored compatibility metadata call must not return');
assert.match(social,/await neonBetterAuthConfirmUsername\(saved,authUser\)/);
assert.match(social,/user\.neon_auth_id&&metadata\.displayName/,'native directory label survives next sign-in');
assert.match(migration,/interval '720 hours'/);
assert.match(migration,/pg_advisory_xact_lock/);
assert.match(migration,/l\.provider='neon' and l\.account_id=new\.user_id and l\.subject=u\.id::text/,
 'native label updates must use the private original-ID binding, never an email guess');
assert.doesNotMatch(migration,/set\s+(?:email|password|role)\s*=/i);
assert.match(migration,/revoke all on function oz_identity\.sync_native_username\(\) from public,anonymous,authenticated/);
assert.match(migration,/get_my_outpost_zero_username\(\)[\s\S]*sp\.user_id=oz_identity\.game_user_id\(\)/,'saved-name lookup must derive the actor from the signed database identity');
assert.match(migration,/if wanted=current_username then[\s\S]{0,300}update public\.social_profiles sp set handle=wanted/,'retrying an already-saved name must repair the failed native label sync');
assert.match(networking,/const confirmed=await neonBetterAuthConfirmUsername\('',linkedUser\)/,'future sign-ins must restore the committed username from Neon');
